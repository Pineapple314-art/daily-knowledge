// 获取分类列表
function getCategories() {
  const categories = [...new Set(knowledgeBase.map(item => item.category))];
  return categories;
}

// 获取随机知识
function getRandomKnowledge(excludeIds = []) {
  const available = knowledgeBase.filter(item => !excludeIds.includes(item.id));
  if (available.length === 0) return null;
  const randomIndex = Math.floor(Math.random() * available.length);
  return available[randomIndex];
}

// 获取每日知识（基于日期种子，确保同一天得到同一条）
function getDailyKnowledge(date = new Date()) {
  const dateStr = date.toDateString();
  // 使用日期字符串生成伪随机索引
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    const char = dateStr.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  const index = Math.abs(hash) % knowledgeBase.length;
  return knowledgeBase[index];
}

// 按类型筛选
function getByType(type) {
  return knowledgeBase.filter(item => item.type === type);
}

// 按分类筛选
function getByCategory(category) {
  return knowledgeBase.filter(item => item.category === category);
}

// 获取统计信息
function getStats() {
  return {
    total: knowledgeBase.length,
    categories: getCategories().length,
    coldCount: getByType('cold').length,
    hotCount: getByType('hot').length
  };
}
